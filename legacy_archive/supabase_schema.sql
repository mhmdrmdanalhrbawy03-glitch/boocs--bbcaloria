-- Supabase schema for the Baccalaureate Library
-- Run this file once in Supabase SQL Editor.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'student' check (role in ('student','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.books (
  id bigint primary key,
  title text not null,
  icon text not null default '📚',
  cat text not null,
  description text not null default '',
  url text not null,
  date bigint not null default 0,
  popular integer not null default 0,
  is_new boolean not null default false,
  series text,
  is_folder boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, book_id)
);

create table if not exists public.activity_events (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id bigint references public.books(id) on delete set null,
  event_type text not null check (event_type in ('open','download','favorite_add','favorite_remove')),
  created_at timestamptz not null default now(),
  meta jsonb not null default '{}'::jsonb
);

create table if not exists public.notifications (
  id bigint primary key generated by default as identity,
  book_id bigint references public.books(id) on delete cascade,
  title text not null,
  description text not null default '',
  category text not null default 'محتوى جديد',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

