-- Keep timestamps current when an existing row is edited.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_profiles_updated_at on public.profiles;
create trigger trg_profiles_updated_at before update on public.profiles for each row execute function public.set_updated_at();
drop trigger if exists trg_books_updated_at on public.books;
create trigger trg_books_updated_at before update on public.books for each row execute function public.set_updated_at();

create index if not exists idx_books_cat on public.books(cat);
create index if not exists idx_books_date on public.books(date desc);
create index if not exists idx_activity_user_created on public.activity_events(user_id, created_at desc);

-- Auto-create a profile row for every new Supabase Auth user.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name) values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Admin helper: reads the role from profiles.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = ''
as $$
  select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

alter table public.profiles enable row level security;
alter table public.books enable row level security;
alter table public.favorites enable row level security;
alter table public.activity_events enable row level security;
alter table public.notifications enable row level security;

drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own on public.profiles for select using (auth.uid() = id or public.is_admin());

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles for update using (auth.uid() = id or public.is_admin()) with check (auth.uid() = id or public.is_admin());

drop policy if exists books_public_read on public.books;
create policy books_public_read on public.books for select using (true);

drop policy if exists books_admin_write on public.books;
create policy books_admin_write on public.books for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists notifications_public_read on public.notifications;
create policy notifications_public_read on public.notifications for select using (is_active = true);

drop policy if exists notifications_admin_write on public.notifications;
create policy notifications_admin_write on public.notifications for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists favorites_own_select on public.favorites;
create policy favorites_own_select on public.favorites for select using (auth.uid() = user_id);
drop policy if exists favorites_own_insert on public.favorites;
create policy favorites_own_insert on public.favorites for insert with check (auth.uid() = user_id);
drop policy if exists favorites_own_update on public.favorites;
create policy favorites_own_update on public.favorites for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists favorites_own_delete on public.favorites;
create policy favorites_own_delete on public.favorites for delete using (auth.uid() = user_id);

drop policy if exists activity_own_select on public.activity_events;
create policy activity_own_select on public.activity_events for select using (auth.uid() = user_id);
drop policy if exists activity_own_insert on public.activity_events;
create policy activity_own_insert on public.activity_events for insert with check (auth.uid() = user_id);

